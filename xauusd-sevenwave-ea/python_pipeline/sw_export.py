"""Train + export the SevenWave AI rater to ONNX (native MT5 contract, zipmap=False).

Training data: Dukascopy 2017-01 .. 2023-12 Liquidity-Wave setups (labels = net R > 0 under the PROFIT-style
management).  2024-2026 is NEVER seen, so every MT5 backtest of 2024-2026 is out of sample for the model.

Outputs:
  MQL5/Files/models/sevenwave_rater.onnx   input "input" float32[1,17] -> "label" int64[1], "probabilities" float32[1,2]
  MQL5/Include/SevenWave/AiModelMeta.mqh   threshold + feature order + training stamp (compiled into the EA)
  python_pipeline/models/sevenwave_rater_meta.json
"""
import os
import json
import numpy as np
import pandas as pd
import onnx
import onnxruntime as ort
from onnxmltools import convert_lightgbm
from onnxmltools.convert.common.data_types import FloatTensorType
import sw_final as F

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ONNX_PATH = os.path.join(ROOT, "MQL5", "Files", "models", "sevenwave_rater.onnx")
META_MQH = os.path.join(ROOT, "MQL5", "Include", "SevenWave", "AiModelMeta.mqh")
META_JSON = os.path.join(ROOT, "python_pipeline", "models", "sevenwave_rater_meta.json")
TRAIN_END_YEAR = 2023

if __name__ == "__main__":
    os.environ["SW_STYLE"] = "profit"
    m1a, tfs, df, X = F.build_all("duka")
    sel = df.year.values <= TRAIN_END_YEAR
    y = (df.r.values > 0).astype(int)
    model, thr = F.train(X[sel], y[sel])
    print(f"trained on {sel.sum()} setups (2017-{TRAIN_END_YEAR}), best_iter={model.best_iteration}, veto threshold={thr:.5f}")
    # re-fit a booster with exactly best_iteration trees so the ONNX graph == the scorer used in research
    import lightgbm as lgb
    params = dict(objective="binary", learning_rate=0.03, num_leaves=7, min_data_in_leaf=60, feature_fraction=0.7,
                  bagging_fraction=0.8, bagging_freq=1, lambda_l2=20.0, verbose=-1, num_threads=2, seed=5)
    n = sel.sum()
    cut = int(n * 0.8)
    Xs, ys = X[sel], y[sel]
    booster = lgb.train(params, lgb.Dataset(Xs[:cut], ys[:cut]), max(1, model.best_iteration))
    onx = convert_lightgbm(booster, initial_types=[("input", FloatTensorType([1, X.shape[1]]))], zipmap=False,
                           target_opset=13)
    os.makedirs(os.path.dirname(ONNX_PATH), exist_ok=True)
    onnx.save(onx, ONNX_PATH)
    sess = ort.InferenceSession(ONNX_PATH)
    outs = [o.name for o in sess.get_outputs()]
    print("ONNX inputs:", [(i.name, i.shape, i.type) for i in sess.get_inputs()], "outputs:", outs)
    # parity: onnx vs booster on 300 random rows
    rs = np.random.default_rng(0).choice(len(X), 300, replace=False)
    p_ref = booster.predict(X[rs])
    p_onx = np.array([sess.run(None, {"input": X[i:i + 1].astype(np.float32)})[1][0, 1] for i in rs])
    print(f"ONNX parity max |diff| = {np.max(np.abs(p_ref - p_onx)):.2e}")
    # threshold from the refit booster on the same validation slice
    pv = booster.predict(Xs[cut:])
    thr2 = float(np.quantile(pv, F.VETO_Q))
    p_all = booster.predict(X)
    print(f"veto threshold (refit) = {thr2:.5f}; share vetoed 2024+: {(p_all[~sel] < thr2).mean():.2%}")
    meta = dict(features=F.FEATS, threshold=thr2, train_years=f"2017-{TRAIN_END_YEAR}", n_train=int(sel.sum()),
                trees=int(max(1, model.best_iteration)), label="net R > 0 under PROFIT management",
                streams=list(F.L3.STREAMS.keys()))
    os.makedirs(os.path.dirname(META_JSON), exist_ok=True)
    json.dump(meta, open(META_JSON, "w"), indent=2)
    os.makedirs(os.path.dirname(META_MQH), exist_ok=True)
    with open(META_MQH, "w", encoding="utf-8") as fh:
        fh.write("//+------------------------------------------------------------------+\n")
        fh.write("//| AiModelMeta.mqh - generated by python_pipeline/sw_export.py      |\n")
        fh.write("//+------------------------------------------------------------------+\n")
        fh.write("#ifndef SEVENWAVE_AIMODELMETA_MQH\n#define SEVENWAVE_AIMODELMETA_MQH\n")
        fh.write(f"#define SW_AI_FEATURES {len(F.FEATS)}\n")
        fh.write(f"#define SW_AI_THRESHOLD {thr2:.8f}\n")
        fh.write(f"#define SW_AI_TRAIN_STAMP \"Duka 2017-{TRAIN_END_YEAR}, {int(sel.sum())} setups, {meta['trees']} trees\"\n")
        fh.write("// feature order: " + ", ".join(F.FEATS) + "\n#endif\n")
    # dump a feature/score sample for MQL5 parity checks
    df.assign(p=p_all).to_pickle(os.path.join(F.OUT, "data", "export_scores_duka.pkl"))
    print("written:", ONNX_PATH, META_MQH, META_JSON)
