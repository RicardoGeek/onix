"""Generate MQL5/Include/SevenWave/NewsDays.mqh from the MQL5 economic-calendar export (MQL5/Scripts/SW_CalendarExport.mq5).

Key US releases (high importance): NFP, CPI family, Core PCE, GDP q/q, Retail Sales, Fed rate decision.  The EA skips NEW
first positions on the UTC days of these releases (study 43/44: setups on those days averaged -0.09R vs +0.37R otherwise).
The Strategy Tester has no calendar, so the days are embedded; live, the EA also asks the terminal's calendar by event id.
  python sw_newsdays.py
"""
import os
import numpy as np
import pandas as pd
import sw_data as SD

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = r"C:\Users\faker\AppData\Roaming\MetaQuotes\Terminal\Common\Files\sw_calendar_us.csv"
PAT = "Nonfarm Payrolls|^CPI|Core CPI|Fed Interest Rate Decision|FOMC Statement|GDP q/q|Retail Sales m/m|PCE"

cal = pd.read_csv(SRC)
cal["t"] = cal.time_srv.values.astype(np.int64)   # the MQL5 calendar times are already UTC (NFP minute = 15x M1 range)
key = cal[(cal.importance == 3) & cal.event.str.contains(PAT, regex=True)]
ids = sorted(key.event_id.unique().tolist())
days = np.unique(key.t.values // 86400).astype(int)
lines = ["//+------------------------------------------------------------------+",
         "//| NewsDays.mqh - generated by python_pipeline/sw_newsdays.py        |",
         f"//| key US release days (UTC day numbers), {pd.Timestamp(days[0] * 86400, unit='s').date()} .. {pd.Timestamp(days[-1] * 86400, unit='s').date()}  |",
         "//+------------------------------------------------------------------+",
         "#ifndef SEVENWAVE_NEWSDAYS_MQH", "#define SEVENWAVE_NEWSDAYS_MQH",
         f"#define SW_NEWS_NDAYS {len(days)}", f"#define SW_NEWS_NIDS {len(ids)}",
         f"const long SW_NEWS_IDS[SW_NEWS_NIDS] = {{{', '.join(str(i) for i in ids)}}};"]
body = [", ".join(str(d) for d in days[i:i + 16]) for i in range(0, len(days), 16)]
lines.append("const int SW_NEWS_DAYS[SW_NEWS_NDAYS] =\n  {\n   " + ",\n   ".join(body) + "\n  };")
lines.append("#endif")
out = os.path.join(ROOT, "MQL5", "Include", "SevenWave", "NewsDays.mqh")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"wrote {out}: {len(days)} days, {len(ids)} event ids")

# ---- NFP releases with actual + forecast (stream N: trade the surprise from +5 min; study 45)
nfp = cal[(cal.event_id == 840030016)].drop_duplicates("t").sort_values("t")
nfp = nfp[np.isfinite(nfp.actual) & np.isfinite(nfp.forecast)]
L = ["//+------------------------------------------------------------------+",
     "//| NfpTable.mqh - generated by python_pipeline/sw_newsdays.py        |",
     "//| US Nonfarm Payrolls: release time (UTC), actual, forecast (k)     |",
     "//+------------------------------------------------------------------+",
     "#ifndef SEVENWAVE_NFPTABLE_MQH", "#define SEVENWAVE_NFPTABLE_MQH",
     "#define SW_NFP_EVENT_ID 840030016", f"#define SW_NFP_N {len(nfp)}"]
L.append("const long   SW_NFP_T[SW_NFP_N] = {" + ", ".join(str(int(x)) for x in nfp.t.values) + "};")
L.append("const double SW_NFP_ACT[SW_NFP_N] = {" + ", ".join(f"{x:.3f}" for x in nfp.actual.values) + "};")
L.append("const double SW_NFP_FC[SW_NFP_N] = {" + ", ".join(f"{x:.3f}" for x in nfp.forecast.values) + "};")
L.append("#endif")
out2 = os.path.join(ROOT, "MQL5", "Include", "SevenWave", "NfpTable.mqh")
open(out2, "w", encoding="utf-8").write("\n".join(L) + "\n")
print(f"wrote {out2}: {len(nfp)} NFP releases with actual + forecast, last {pd.Timestamp(nfp.t.values[-1], unit='s')} UTC")
